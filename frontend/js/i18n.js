const dates = new Map();
export function dateText(value) {
  if (!value) return "—";
  const date = new Date(value);
  const options = {
    dateStyle: "medium",
    timeStyle: "short",
    calendar: "gregory",
  };
  const english = new Intl.DateTimeFormat("en-GB", options).format(date);
  dates.set(english, new Intl.DateTimeFormat("ar-EG", options).format(date));
  return english;
}
export function translateText(source, language = "ar") {
  if (language !== "ar") return source;
  if (translations[source]) return translations[source];
  if (source.startsWith("＋ ") && translations[source.slice(2)])
    return `＋ ${translations[source.slice(2)]}`;
  if (translations[source.replace(/\s+/g, " ")])
    return translations[source.replace(/\s+/g, " ")];
  let text = source;
  for (const [english, arabic] of dates)
    text = text.replaceAll(english, arabic);
  return text
    .replace(/^(\d+) available out of (\d+)$/, "$1 متاح من أصل $2")
    .replace(/^(\d+) available to add$/, "$1 متاح للإضافة")
    .replace(/^(\d+) requested$/, "$1 مطلوب")
    .replace(
      /^(\d+) equipment types? · (\d+) physical items?$/,
      "$1 نوع معدات · $2 قطعة فعلية",
    )
    .replace(
      /^(\d+) items? returned; (\d+) marked lost; (\d+) still outstanding\.$/,
      "تم إرجاع $1 قطعة؛ وتسجيل $2 كمفقودة؛ وما زالت $3 قطعة مستعارة.",
    )
    .replace(/^(\d+) items? issued successfully\.$/, "تم تسليم $1 قطعة بنجاح.")
    .replace(
      /^Equipment created with (\d+) available items\.$/,
      "تم إنشاء المعدات مع $1 قطعة متاحة.",
    )
    .replace(/^Created (\d+) physical items$/, "تم إنشاء $1 قطعة فعلية")
    .replace(
      /^(.+) · (\d+) currently available out of (\d+)$/,
      "$1 · $2 متاح حالياً من أصل $3",
    )
    .replace(/^Return (.+)$/, "إرجاع $1")
    .replace(
      /^Update access for (.+)\. Existing sessions will be revoked\.$/,
      "تحديث صلاحية الوصول لحساب $1. ستُلغى الجلسات الحالية.",
    )
    .replace(
      /^(\d+) items, ([A-Z]+)\. Codes: (.+)\. Automatically generated codes are provisional until creation\.$/,
      (_, count, condition, codes) =>
        `${count} قطعة، ${translations[condition] || condition}. الرموز: ${codes}. الرموز التلقائية مؤقتة حتى إتمام الإنشاء.`,
    )
    .replace(
      /^Retire available items, keep the history for (.+), and hide it from the active catalog\.$/,
      "إخراج القطع المتاحة من الخدمة، والاحتفاظ بسجل $1 وإخفائه من الدليل الحالي.",
    )
    .replace(
      /^(Activate|Deactivate) (.+)\?$/,
      (_, action, name) =>
        `${action === "Activate" ? "تفعيل" : "تعطيل"} ${name}؟`,
    )
    .replace(/^(.+) quantity to add$/, "$1: الكمية للإضافة")
    .replace(/^(.+) cart quantity$/, "$1: الكمية في السلة")
    .replace(
      /^Issued (.+) · Due (.+) · Keeper (.+)$/,
      "تاريخ التسليم $1 · موعد الإرجاع $2 · أمين المخزن $3",
    )
    .replace(/^From (.+) to (.+)$/, "من $1 إلى $2")
    .replace(/^Borrowing BR-([A-Z0-9]+)$/, "استعارة BR-$1")
    .replace(/^Request RQ-([A-Z0-9]+)$/, "طلب RQ-$1")
    .replace(
      /^Good (morning|afternoon|evening), (.+)\. Here’s the latest from your storage\.$/,
      "مرحباً، $2. إليك آخر أخبار المخزن.",
    )
    .replace(
      /^(\d+) records · Page (\d+) of (\d+)$/,
      "$1 سجل · الصفحة $2 من $3",
    )
    .replace(/^(\d+) equipment types$/, "$1 نوع من المعدات");
}
