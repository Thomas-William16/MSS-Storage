// Status labels appear in title case, capitals and lowercase across the app.
for (const [key, value] of Object.entries(franco)) {
  franco[key.toLowerCase()] ??= value;
  franco[key.toUpperCase()] ??= value;
}

export function translateFranco(source) {
  const key = source.replace(/\s+/g, " ");
  if (franco[key]) return franco[key];
  if (key.startsWith("＋ ") && franco[key.slice(2)])
    return `＋ ${franco[key.slice(2)]}`;
  return source
    .replace(/^(\d+) available out of (\d+)$/, "$1 meta7 men asl $2")
    .replace(/^(\d+) available to add$/, "$1 meta7 lel edafa")
    .replace(/^(\d+) requested$/, "$1 matloub")
    .replace(
      /^(\d+) equipment types? · (\d+) physical items?$/,
      "$1 no3 mo3eddat · $2 2et3a fe3leya",
    )
    .replace(
      /^(\d+) items? returned; (\d+) marked lost; (\d+) still outstanding\.$/,
      "$1 2et3a rege3et; $2 maf2ouda; $3 lessa meste3ara.",
    )
    .replace(
      /^(\d+) items? issued successfully\.$/,
      "$1 2et3a et sallemet benaga7.",
    )
    .replace(
      /^Equipment created with (\d+) available items\.$/,
      "El mo3eddat et3amalet ma3 $1 2et3a meta7a.",
    )
    .replace(/^Created (\d+) physical items$/, "Et3amal $1 2et3a fe3leya")
    .replace(
      /^(.+) · (\d+) currently available out of (\d+)$/,
      "$1 · $2 meta7 delwa2ty men asl $3",
    )
    .replace(/^Return (.+)$/, "Ragga3 $1")
    .replace(
      /^Update access for (.+)\. Existing sessions will be revoked\.$/,
      "7addeth sala7eyat $1. El galsat el 7aleya hatetleghi.",
    )
    .replace(
      /^(\d+) items, ([A-Z]+)\. Codes: (.+)\. Automatically generated codes are provisional until creation\.$/,
      (_, count, condition, codes) =>
        `${count} 2et3a, ${franco[condition] || condition}. El codes: ${codes}. El codes el tel2a2eya mo2a22ata le7ad el ensha2.`,
    )
    .replace(
      /^Retire available items, keep the history for (.+), and hide it from the active catalog\.$/,
      "Kharrag el 2eta3 el meta7a men el khedma, e7faz segel $1, we ekhfeeha men el daleel el 7ali.",
    )
    .replace(
      /^(Activate|Deactivate) (.+)\?$/,
      (_, action, name) =>
        `${action === "Activate" ? "Fa33al" : "3attal"} ${name}?`,
    )
    .replace(/^(.+) quantity to add$/, "$1: el kemmeya lel edafa")
    .replace(/^(.+) cart quantity$/, "$1: el kemmeya fi el salla")
    .replace(
      /^Issued (.+) · Due (.+) · Keeper (.+)$/,
      "Et sallam $1 · El erga3 $2 · Ameen el makhzan $3",
    )
    .replace(/^From (.+) to (.+)$/, "Men $1 le7ad $2")
    .replace(/^Borrowing BR-([A-Z0-9]+)$/, "Este3ara BR-$1")
    .replace(/^Request RQ-([A-Z0-9]+)$/, "Talab RQ-$1")
    .replace(
      /^Good (morning|afternoon|evening), (.+)\. Here’s the latest from your storage\.$/,
      "Ahlan, $2. Di akher akhbar el makhzan.",
    )
    .replace(
      /^(\d+) records · Page (\d+) of (\d+)$/,
      "$1 segel · Saf7a $2 men $3",
    )
    .replace(/^(\d+) equipment types$/, "$1 no3 mo3eddat");
}
